// Generates packages/shared/src/abis.ts from Foundry artifacts. Run after `forge build`.
import { readFileSync, writeFileSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const out = join(root, "contracts", "out");
const contracts = [
  ["OpenShareCore", "OpenShareCore"],
  ["OpenShareToken", "OpenShareToken"],
  ["BondVault", "BondVault"],
  ["RoleRegistry", "RoleRegistry"],
  ["ComplianceRegistry", "ComplianceRegistry"],
  ["PriceOracle", "PriceOracle"],
  ["AttestedPledgeVerifier", "AttestedPledgeVerifier"],
  ["ReclaimPledgeVerifier", "ReclaimPledgeVerifier"],
  ["OpenShareHook", "OpenShareHook"],
  ["MockUSDT", "MockUSDT"],
  ["PoolSwapTest", "PoolSwapTest"],
  ["PoolModifyLiquidityTest", "PoolModifyLiquidityTest"],
  ["PoolManager", "PoolManager"],
];
let ts = "// AUTO-GENERATED by scripts/gen-abis.mjs. Do not edit.\n\n";
for (const [file, name] of contracts) {
  const art = JSON.parse(readFileSync(join(out, `${file}.sol`, `${name}.json`), "utf8"));
  ts += `export const ${name[0].toLowerCase() + name.slice(1)}Abi = ${JSON.stringify(art.abi)} as const;\n\n`;
}
writeFileSync(join(root, "packages", "shared", "src", "abis.ts"), ts);
console.log("wrote packages/shared/src/abis.ts");
